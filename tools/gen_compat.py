"""Generate include/neoj2k/neoj2k_openjpeg.h, the compile-time OpenJPEG compatibility header.

Every nj2k_* / NJ2K_* name of include/neoj2k/neoj2k.h gets the OpenJPEG name that maps onto it
(opj_* / OPJ_*, JPWL_* for NJ2K_JPWL_*, the bare enum tags), except neo-j2k's own names.

usage: gen_compat.py            write the header
       gen_compat.py --check    exit 1 if the committed header is stale, or if any opj_* / OPJ_* /
                                JPWL_* name of the oracle's openjpeg.h has no mapping
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
API = os.path.join(ROOT, "include", "neoj2k", "neoj2k.h")
OUT = os.path.join(ROOT, "include", "neoj2k", "neoj2k_openjpeg.h")
OPENJPEG = os.path.join(ROOT, "oracle", "openjp2", "openjpeg.h")

# neo-j2k's own names: no OpenJPEG counterpart, or a different meaning
OWN = {
    "NEOJ2K_H", "NJ2K_STATIC", "NJ2K_BUILDING",
    "NJ2K_VERSION_MAJOR", "NJ2K_VERSION_MINOR", "NJ2K_VERSION_PATCH",
    "NJ2K_ENGINE_STRING_MAX", "nj2k_engine_string", "nj2k_cpu_supported",
}
ENUM_TAGS = ["RSIZ_CAPABILITIES", "CINEMA_MODE", "PROG_ORDER", "COLOR_SPACE", "CODEC_FORMAT"]
# names in openjpeg.h that are not API: its include guard, its build switches, INLINE
NOT_API = {"OPENJPEG_H", "OPJ_EXPORTS", "OPJ_STATIC", "DLL_EXPORT", "INLINE", "opj_config",
           "OPJ_VERSION_MAJOR", "OPJ_VERSION_MINOR", "OPJ_VERSION_BUILD"}

HEADER = """/*
 * SPDX-License-Identifier: BSD-2-Clause
 * Copyright (c) 2026, Anne Skydancer (neo-j2k)
 *
 * OpenJPEG source compatibility: include this header instead of <openjpeg.h> (or put
 * include/neoj2k/compat on the include path, whose openjpeg.h includes it) and OpenJPEG code
 * compiles against neo-j2k unchanged. Every opj_* / OPJ_* name becomes the nj2k_* / NJ2K_* name
 * of the same declaration; the program links neoj2k. Defining OPJ_STATIC selects the static
 * library, as it does for OpenJPEG.
 *
 * Generated by tools/gen_compat.py from neoj2k.h; do not edit. CI checks that it is current and
 * that it maps every name of OpenJPEG 2.5.4's openjpeg.h.
 */
#ifndef NEOJ2K_OPENJPEG_H
#define NEOJ2K_OPENJPEG_H

#if defined(OPJ_STATIC) && !defined(NJ2K_STATIC)
#define NJ2K_STATIC
#endif

#include "neoj2k.h"

/* The OpenJPEG API level this mirrors (opj_config.h); neo-j2k's own is NJ2K_VERSION_*. */
#define OPJ_VERSION_MAJOR 2
#define OPJ_VERSION_MINOR 5
#define OPJ_VERSION_BUILD 4
"""


def api_names():
    with open(API, encoding="utf-8") as f:
        text = f.read()
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return sorted(set(re.findall(r"\b(?:nj2k|NJ2K)_\w+", text)) - OWN)


def openjpeg_name(name):
    if name.startswith("NJ2K_JPWL_"):
        return name[len("NJ2K_"):]
    if name.startswith("NJ2K_"):
        return "OPJ_" + name[len("NJ2K_"):]
    return "opj_" + name[len("nj2k_"):]


def generate():
    lines = [HEADER]
    lines.append("/* names */")
    for name in api_names():
        lines.append("#define %s %s" % (openjpeg_name(name), name))
    lines.append("")
    lines.append("/* openjpeg.h's enum tags, which OpenJPEG leaves unprefixed */")
    for tag in ENUM_TAGS:
        lines.append("#define %s NJ2K_%s" % (tag, tag))
    lines.append("")
    lines.append("#endif /* NEOJ2K_OPENJPEG_H */")
    return "\n".join(lines) + "\n"


def openjpeg_names():
    with open(OPENJPEG, encoding="utf-8") as f:
        text = f.read()
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return set(re.findall(r"\b(?:opj|OPJ|JPWL)_\w+", text)) | set(
        t for t in ENUM_TAGS if re.search(r"\benum\s+%s\b" % t, text))


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        problems = []
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                problems.append("include/neoj2k/neoj2k_openjpeg.h is stale: run tools/gen_compat.py")
        mapped = set(re.findall(r"^#define (\w+) ", text, flags=re.M))
        for name in sorted(openjpeg_names() - mapped - NOT_API):
            problems.append("openjpeg.h name without a mapping: " + name)
        for p in problems:
            print("gen_compat: " + p, file=sys.stderr)
        if problems:
            return 1
        print("gen_compat: neoj2k_openjpeg.h is current and maps all %d OpenJPEG names" %
              len(openjpeg_names() - NOT_API))
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("gen_compat: wrote %s (%d names)" % (os.path.relpath(OUT, ROOT), len(api_names())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
