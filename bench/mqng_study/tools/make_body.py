"""Writes <out>: the decoder of src/t1.cpp (the MQ decoder, the passes, t1_decode_cblk) as a body that a
study variant includes inside its own namespace. src/ is only read. What the body leaves to the variant:
  - the types opj_mqc_t, opj_t1_t, opj_mqc_state_t (defined before the include);
  - with STUDY_OWN_MQ "<file>": the whole MQ region (mqc_inl.h and mqc.c: decode, raw decode, renorm,
    init, finish, reset, setstate, DOWNLOAD/UPLOAD) and the two setcurctx macros come from <file>;
  - with STUDY_OVR_<macro> defined: that pass macro is the variant's own (defined before the include);
  - STUDY_PASS_BEGIN() / STUDY_PASS_END(passtype, type) around each pass (empty by default).
The entry point is renamed decode_cblk(opj_t1_t&, const T1Block&, const Messages&).
usage: make_body.py <repo> <out>"""
import os
import sys

repo, out = sys.argv[1], sys.argv[2]
src = open(os.path.join(repo, 'src', 't1.cpp'), encoding='utf-8').read()


def cut(text, a, b):
    i = text.index(a)
    j = text.index(b, i)
    return text[i:j]


def rep(text, a, b):
    assert text.count(a) == 1, ('not unique', a[:80], text.count(a))
    return text.replace(a, b)


# the anonymous namespace up to the T1 members, then t1_decode_cblk
head = cut(src, "namespace {\n\n// OpenJPEG's names", "bool T1::ready(")
cblk = cut(src, "// opj_t1_decode_cblk. The code-block's chunks", "#if defined(NJ2K_T1_TRACE)\nT1Trace g_t1_trace")

for u in ("using opj_mqc_state_t = MqState;\n", "using opj_mqc_t = Mqc;\n", "using opj_t1_t = T1;\n"):
    head = rep(head, u, "")

head = rep(head, "#define opj_mqc_setcurctx(mqc, ctxno) (mqc)->curctx = &(mqc)->ctxs[(OPJ_UINT32)(ctxno)]\n",
           "#if !defined(STUDY_OWN_MQ)\n#define opj_mqc_setcurctx(mqc, ctxno) (mqc)->curctx = &(mqc)->ctxs[(OPJ_UINT32)(ctxno)]\n#endif\n")
head = rep(head, "#define opj_t1_setcurctx(curctx, ctxno) curctx = &(mqc)->ctxs[(OPJ_UINT32)(ctxno)]\n",
           "#if !defined(STUDY_OWN_MQ)\n#define opj_t1_setcurctx(curctx, ctxno) curctx = &(mqc)->ctxs[(OPJ_UINT32)(ctxno)]\n#endif\n")
# the MQ region
a = "// ---- mqc_inl.h: the MQ decoder ----\n"
b = "// ---- t1_luts.h: the context tables (decoding) ----\n"
i, j = head.index(a), head.index(b)
head = head[:i] + "#if defined(STUDY_OWN_MQ)\n#include STUDY_OWN_MQ\n#else\n" + head[i:j] + "#endif\n" + head[j:]


def wrap_macro(text, name):
    k = text.index("#define " + name + "(")
    e = k
    while True:
        nl = text.index("\n", e)
        line = text[e:nl]
        e = nl + 1
        if not line.rstrip().endswith("\\"):
            break
    return text[:k] + "#if !defined(STUDY_OVR_" + name + ")\n" + text[k:e] + "#endif\n" + text[e:]


for m in ("opj_t1_dec_sigpass_step_mqc_macro", "opj_t1_dec_refpass_step_mqc_macro", "opj_t1_dec_clnpass_step_macro",
          "opj_t1_dec_clnpass_internal", "opj_t1_dec_sigpass_mqc_internal", "opj_t1_dec_refpass_mqc_internal"):
    head = wrap_macro(head, m)

# the cleanup pass's AGG decision, which a variant may replace (STUDY_AGG)
head = rep(head, "                opj_t1_setcurctx(curctx, T1_CTXNO_AGG); \\\n"
                 "                opj_mqc_decode_macro(v, mqc, curctx, a, c, ct); \\\n",
           "                STUDY_AGG(v, mqc, curctx, a, c, ct); \\\n")
head = ("#if !defined(STUDY_AGG)\n#define STUDY_AGG(v, mqc, curctx, a, c, ct) \\\n"
        "    { opj_t1_setcurctx(curctx, T1_CTXNO_AGG); opj_mqc_decode_macro(v, mqc, curctx, a, c, ct); }\n#endif\n" + head)

cblk = rep(cblk, "bool t1_decode_cblk(T1& t1_ref, const T1Block& b, const Messages& msg) noexcept",
           "bool decode_cblk(opj_t1_t& t1_ref, const T1Block& b, const Messages& msg) noexcept")
cblk = rep(cblk, "            switch (passtype) {\n", "            STUDY_PASS_BEGIN();\n            switch (passtype) {\n")
cblk = rep(cblk, "            }\n\n            if ((cblksty & J2K_CCP_CBLKSTY_RESET) && type == T1_TYPE_MQ) {",
           "            }\n            STUDY_PASS_END(passtype, type);\n\n            if ((cblksty & J2K_CCP_CBLKSTY_RESET) && type == T1_TYPE_MQ) {")

pre = ("// generated by bench/mqng_study/tools/make_body.py from src/t1.cpp: do not edit\n"
       "#if !defined(STUDY_PASS_BEGIN)\n#define STUDY_PASS_BEGIN()\n#endif\n"
       "#if !defined(STUDY_PASS_END)\n#define STUDY_PASS_END(p, t)\n#endif\n")
os.makedirs(os.path.dirname(out), exist_ok=True)
text = pre + head + "\n" + cblk
old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
if old != text:
    open(out, 'w', encoding='utf-8', newline='\n').write(text)
