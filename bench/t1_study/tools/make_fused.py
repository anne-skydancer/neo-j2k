"""Writes bench/t1_study/proto/enc_t1_fused_body.inc: src/enc_t1.cpp with the MQ coder's registers and
context states held in locals for each pass (the fused design), the states as byte indices into a packed
4-byte table, renormalisation by count-leading-zeros, and STUDY_BRANCHLESS choosing the MPS/LPS select
(1) or branch (0). The passes, the contexts, the distortion and the rates are the library's text.
usage: make_fused.py <repo>"""
import os
import sys

repo = sys.argv[1]
src = open(os.path.join(repo, 'src', 'enc_t1.cpp'), encoding='utf-8').read()


def rep(a, b, unique=True):
    global src
    n = src.count(a)
    assert n >= 1, a[:100]
    if unique:
        assert n == 1, ('not unique', a[:100], n)
    src = src.replace(a, b)


rep('namespace nj2k::detail {\n\nnamespace {\n', 'namespace nj2k::STUDY_NS {\nusing namespace nj2k::detail;\n\nnamespace {\n')
rep('}  // namespace nj2k::detail\n',
    'std::size_t enc_t1_size() noexcept { return sizeof(EncT1); }\n\n}  // namespace nj2k::STUDY_NS\n')
rep('#include <cstring>\n', '#include <bit>\n#include <cstring>\n')

MQ = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'fused_mq.inc'), encoding='utf-8').read()
start = src.index('struct MqEnc {')
end = src.index('}  // namespace\n', start)
src = src[:start] + MQ + src[end:]

# the steps take the pass's coder
for step in ['enc_sigpass_step(EncT1* t1,', 'enc_refpass_step(EncT1* t1,', 'enc_clnpass_step(EncT1* t1,']:
    rep('inline void ' + step, '__forceinline void ' + step + ' Mq& mqr,')
rep('    MqEnc* mqc = &t1->mqc;\n    OPJ_UINT32 v;\n    OPJ_UINT32 const flags = *flagsp;',
    '    Mq* mqc = &mqr;\n    OPJ_UINT32 v;\n    OPJ_UINT32 const flags = *flagsp;')
rep('    MqEnc* mqc = &t1->mqc;\n    OPJ_UINT32 v;\n    if ((flags &', '    Mq* mqc = &mqr;\n    OPJ_UINT32 v;\n    if ((flags &')
rep('    MqEnc* mqc = &t1->mqc;\n    OPJ_UINT32 v;\n    OPJ_UINT32 ci;', '    Mq* mqc = &mqr;\n    OPJ_UINT32 v;\n    OPJ_UINT32 ci;')
rep('inline std::uint8_t getctxno_zc(const MqEnc* mqc,', 'inline std::uint8_t getctxno_zc(const Mq* mqc,')
rep('enc_sigpass_step(t1, f,', 'enc_sigpass_step(t1, mqr, f,', unique=False)
rep('enc_refpass_step(t1, flags,', 'enc_refpass_step(t1, mqr, flags,', unique=False)
rep('enc_refpass_step(t1, *f,', 'enc_refpass_step(t1, mqr, *f,', unique=False)
rep('enc_clnpass_step(t1, f,', 'enc_clnpass_step(t1, mqr, f,', unique=False)
# the pass bodies with the coder in a local, and wrappers that load and save it
for name in ['enc_sigpass', 'enc_refpass', 'enc_clnpass']:
    rep('void %s(EncT1* t1, OPJ_INT32 bpno, OPJ_INT32* nmsedec) noexcept\n{' % name,
        '__forceinline void %s_body(EncT1* t1, Mq& mqr, OPJ_INT32 bpno, OPJ_INT32* nmsedec) noexcept\n{' % name)
rep('    MqEnc* mqc = &t1->mqc;\n    const OPJ_INT32* datap = t1->data;\n    opj_flag_t* f = &T1_FLAGS(0, 0);',
    '    Mq* mqc = &mqr;\n    const OPJ_INT32* datap = t1->data;\n    opj_flag_t* f = &T1_FLAGS(0, 0);')
wrappers = ''
for name in ['enc_sigpass', 'enc_refpass', 'enc_clnpass']:
    wrappers += ('void %s(EncT1* t1, OPJ_INT32 bpno, OPJ_INT32* nmsedec) noexcept\n{\n#if STUDY_LOCALS\n'
                 '    Mq mqr = t1->mqc;\n    %s_body(t1, mqr, bpno, nmsedec);\n    t1->mqc = mqr;\n#else\n'
                 '    %s_body(t1, t1->mqc, bpno, nmsedec);\n#endif\n}\n\n') % (name, name, name)
rep('double getwmsedec(', wrappers + 'double getwmsedec(')
# STUDY_PASSTIME: TSC cycles a pass type (g_pass_cycles), for the per-pass profile of a candidate
rep('        switch (passtype) {\n        case 0:',
    '#if STUDY_PASSTIME\n        const std::uint64_t pt0 = __rdtsc();\n#endif\n        switch (passtype) {\n        case 0:')
rep('            enc_clnpass(t1, bpno, &nmsedec);\n            break;\n        }\n',
    '            enc_clnpass(t1, bpno, &nmsedec);\n            break;\n        }\n#if STUDY_PASSTIME\n'
    '        g_pass_cycles[passtype] += __rdtsc() - pt0;\n#endif\n')
rep('using namespace nj2k::detail;\n', 'using namespace nj2k::detail;\ninline std::uint64_t g_pass_cycles[3];\n')
rep('#include <bit>\n', '#include <bit>\n#include <intrin.h>\n')
out = os.path.join(repo, 'bench', 't1_study', 'proto', 'enc_t1_fused_body.inc')
open(out, 'w', encoding='utf-8', newline='\n').write(
    '// Generated by bench/t1_study/tools/make_fused.py from src/enc_t1.cpp (the fused design). Not the library.\n'
    + src)
print('wrote', out)
